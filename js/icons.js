window.iconMarkup = function iconMarkup(name, className = "") {
  const body = window.IconLibrary[name] || window.IconLibrary.info;
  return `<svg class="icon ${className}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${body}</svg>`;
};

window.hydrateIcons = function hydrateIcons(root = document) {
  root.querySelectorAll("[data-icon]").forEach((node) => {
    if (node.dataset.iconHydrated === "true") return;
    const name = node.dataset.icon;
    node.innerHTML = window.iconMarkup(name);
    node.dataset.iconHydrated = "true";
  });
};
